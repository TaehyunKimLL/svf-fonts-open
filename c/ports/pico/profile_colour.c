/* profile_colour.c - 240 x 240 RGB565 panel: Paperlogy 16 + 18 chain, yellow on dark blue, drawn in 24-row bands.
 * The panel is cleared band by band first (ten shows), then five text bands (y = 16 + 28 i) are drawn and shown. */
#include <stdint.h>
#include <string.h>
#include "display.h"
#include "profile.h"
#include "svf.h"

extern const uint8_t paplg16[], paplg18[]; /* generated by c/bench/mkface.py at build time */
extern const uint32_t paplg16_len, paplg18_len;

const char svf_port_profile_colour[] = "colour";
const char *const svf_port_text[] = {"Pico ST7789 RGB565", "다람쥐 헌 쳇바퀴에 타고파!", "키스의 고유조건은 입술끼리",
                                     "만나야 하고 특별한 기술은", "필요치 않다."};
const int svf_port_text_n = 5;

#define FG 0xFFE0u
#define BG 0x0010u
#define TEXT_X 8
#define BASELINE 19

static uint8_t band[PORT_LCD_W * LINE_H * 2];

static void fill_bg(void)
{
	uint8_t hi = BG >> 8, lo = BG & 0xFF;
	uint8_t a = display_565_bigendian ? hi : lo, b = display_565_bigendian ? lo : hi;
	size_t i;

	for (i = 0; i < sizeof band; i += 2) {
		band[i] = a;
		band[i + 1] = b;
	}
}

void profile_run(void)
{
	static svf_face f16, f18;
	svf_face *faces[2] = {&f16, &f18};
	svf_chain chain;
	svf_target t;
	uint8_t scratch[90];
	volatile const char *marker = svf_port_profile_colour;
	char keep = *marker; /* one volatile read: keeps the marker through -fdata-sections --gc-sections (nm check) */
	int i;

	(void)keep;
	memset(&chain, 0, sizeof chain);
	chain.faces = faces;
	chain.count = 2;
	chain.missing_advance = 6;
	if (svf_open_mapped(&f16, paplg16, paplg16_len) != SVF_OK || svf_open_mapped(&f18, paplg18, paplg18_len) != SVF_OK ||
	    svf_chain_scratch_bytes(&chain) > sizeof scratch ||
	    svf_target_init(&t, SVF_T_RGB565, band, sizeof band, PORT_LCD_W, LINE_H, PORT_LCD_W * 2) != SVF_OK) {
		svf_port_idle();
		return;
	}
	t.fg565 = FG;
	t.bg565 = BG;
	t.flags = display_565_bigendian ? SVF_TF_565_BIGENDIAN : 0;

	fill_bg();
	for (i = 0; i < 10; ++i)
		display_show(band, (int16_t)(LINE_H * i), LINE_H);
	for (i = 0; i < svf_port_text_n; ++i) {
		fill_bg();
		if (svf_draw_utf8(&chain, svf_port_text[i], strlen(svf_port_text[i]), TEXT_X, BASELINE, &t, scratch,
		                  sizeof scratch) != SVF_OK) {
			svf_port_idle();
			return;
		}
		display_show(band, (int16_t)(16 + 28 * i), LINE_H);
	}
}

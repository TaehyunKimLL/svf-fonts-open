/* profile_grey.c - 128 x 128 grey panel: Paperlogy 16 + 18 chain drawn as GRAY8 into one frame, shown once (the
 * driver packs it to the SSD1327's 4 bits a pixel). Text x 4, baselines 17 + 24 i. */
#include <stdint.h>
#include <string.h>
#include "display.h"
#include "profile.h"
#include "svf.h"

#if SVF_GREY_KIND_GRAY8
#define GREY_KIND SVF_T_GRAY8
#else
#error "the grey profile needs a kind: pass -DSVF_GREY_KIND_GRAY8=1 (SVF_GREY_KIND=GRAY8 in CMake)"
#endif

extern const uint8_t paplg16[], paplg18[]; /* generated by c/bench/mkface.py at build time */
extern const uint32_t paplg16_len, paplg18_len;

const char svf_port_profile_grey[] = "grey";
const char *const svf_port_text[] = {"ESP32 GRAY8", "다람쥐 헌", "쳇바퀴에", "타고파!", "안녕하세요"};
const int svf_port_text_n = 5;

static uint8_t frame[GREY_W * GREY_H];

void profile_run(void)
{
	static svf_face f16, f18;
	svf_face *faces[2] = {&f16, &f18};
	svf_chain chain;
	svf_target t;
	uint8_t scratch[90];
	volatile const char *marker = svf_port_profile_grey;
	char keep = *marker; /* one volatile read: keeps the marker through -fdata-sections --gc-sections (nm check) */
	int i;

	(void)keep;
	memset(&chain, 0, sizeof chain);
	chain.faces = faces;
	chain.count = 2;
	chain.missing_advance = 6;
	if (svf_open_mapped(&f16, paplg16, paplg16_len) != SVF_OK || svf_open_mapped(&f18, paplg18, paplg18_len) != SVF_OK ||
	    svf_chain_scratch_bytes(&chain) > sizeof scratch ||
	    svf_target_init(&t, GREY_KIND, frame, sizeof frame, GREY_W, GREY_H, GREY_W) != SVF_OK) {
		svf_port_idle();
		return;
	}
	memset(frame, 0, sizeof frame);
	for (i = 0; i < svf_port_text_n; ++i)
		if (svf_draw_utf8(&chain, svf_port_text[i], strlen(svf_port_text[i]), 4, (int16_t)(17 + 24 * i), &t, scratch,
		                  sizeof scratch) != SVF_OK) {
			svf_port_idle();
			return;
		}
	display_show(frame, 0, GREY_H);
}

#!/usr/bin/env python3
"""mkface.py FACE OUT [--name NAME] [--profile P] [--box B] - writes FACE (an .SVF file) as a C array for the speed probe
(c/bench/bench.c).

OUT gets
    const uint8_t NAME[] BENCH_FACE_ATTR __attribute__((aligned(A))) = {...};
    const uint32_t NAME_len = <bytes>;
with BENCH_FACE_ATTR PROGMEM on AVR (the face stays in flash and is read through SVF_RD8) and empty elsewhere.
NAME defaults to bench_face. Without --profile the bytes are FACE's as they are; with it (a profile name or REC,ROW,TAB,OFF
log2 units, tools/jamoset.py) they are jamoset.relayout of FACE in that profile (--box replaces the profile's ink box
policy). A = 2^max(REC, TAB) of the written bytes, so a record's offset in the file is its address alignment; the
attribute is left out when A is 1. Nothing is written but OUT.
"""
import argparse
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "tools"))
import jamoset  # noqa: E402


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("face")
    ap.add_argument("out")
    ap.add_argument("--name", default="bench_face")
    jamoset.add_profile_args(ap, default=None)
    a = ap.parse_args(argv)
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", a.name):
        ap.error(f"not a C identifier: {a.name}")
    with open(a.face, "rb") as fh:
        data = fh.read()
    profile = jamoset.profile_arg(ap, a)
    if a.box and profile is None:
        ap.error("--box needs --profile")
    try:
        if profile is not None:
            data = jamoset.relayout(data, profile)
        rec, _row, tab, _off = jamoset.parse_svfn(data).layout
    except ValueError as e:
        ap.error(f"{a.face}: {e}")
    align = 1 << max(rec, tab)
    attr = f" __attribute__((aligned({align})))" if align > 1 else ""
    lines = [
        f"/* Generated by c/bench/mkface.py from {a.face.replace('*/', '* /')} ({len(data)} bytes{', profile ' + str(a.profile) if profile is not None else ''}). */",
        "#include <stdint.h>",
        "#ifdef __AVR__",
        "#include <avr/pgmspace.h>",
        "#define BENCH_FACE_ATTR PROGMEM",
        "#else",
        "#define BENCH_FACE_ATTR",
        "#endif",
        f"const uint8_t {a.name}[] BENCH_FACE_ATTR{attr} = {{",
    ]
    for i in range(0, len(data), 24):
        lines.append("\t" + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines += ["};", f"const uint32_t {a.name}_len = {len(data)}u;", ""]
    with open(a.out, "w") as fh:
        fh.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
